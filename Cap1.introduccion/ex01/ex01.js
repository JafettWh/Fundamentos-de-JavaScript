console.log ("Hola mundo"); // Esto se ve en la consola del navegador

/*

MULTIPLES MENSAJES 

console.log permite mostrar información en la consola del navegador. Podemos usarlo para mostrar múltiples mensajes, como se muestra a continuación:
*/

console.log ("Mensaje 1");
console.log ("Mensaje 2");
console.log ("Mensaje 3"); 
console.log ("Mensaje 4");

