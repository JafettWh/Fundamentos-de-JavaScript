// Objetos en JavaScript
let usuario = {
    nombre: "Carlos",
    edad: 25,
    activo: true
}; // Declaración de un objeto "usuario" con propiedades "nombre", "edad" y "activo"

console.log(usuario); // Muestra el objeto completo "usuario" en la consola

// Acceso a las propiedades del objeto
console.log(usuario.nombre); // Muestra el valor de la propiedad "nombre" del objeto "usuario" en la consola
console.log(usuario.edad); // Muestra el valor de la propiedad "edad" del objeto "usuario" en la consola
console.log(usuario.activo); // Muestra el valor de la propiedad "activo" del objeto "usuario" en la consola

// Modificación de las propiedades del objeto
usuario.ciudad = "Cali"; // Agrega una nueva propiedad "ciudad" al objeto "usuario" con el valor "Cali"
console.log(usuario); // Muestra el objeto actualizado "usuario" en la consola